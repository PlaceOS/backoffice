/**
 * Make the subset of the Material Symbols Rounded font that the app uses.
 *
 * The full font is about 420 KB. The app uses a few hundred of its icons, so
 * the first page load gets a small subset font. IconComponent switches to the
 * full font for names that are not in the subset (e.g. icons from server
 * settings), so a missing name costs a download, not a broken icon.
 *
 * Run this when you add icons: `bun config/icon-subset.ts`
 * It needs fontTools: `pip install fonttools brotli`
 */
import { $, Glob } from 'bun';

const FONT = 'src/fonts/material-symbols-rounded.woff2';
const SUBSET = 'src/fonts/material-symbols-rounded-subset.woff2';
const NAMES = 'src/app/ui/icon-subset.ts';

/** Names of the glyphs in the full font */
async function fontGlyphs() {
    const out =
        await $`python3 -c ${'import sys; from fontTools.ttLib import TTFont; print("\\n".join(TTFont(sys.argv[1]).getGlyphOrder()))'} ${FONT}`.text();
    return new Set(out.split('\n').filter(Boolean));
}

/** Words in the source that could be icon names */
async function sourceWords() {
    const words = new Set<string>();
    // Text inside icon elements, e.g. <icon>add</icon> or <icon>{{ a ? 'b' : 'c' }}</icon>
    const icon_tags =
        /<(?:icon|app-icon)\b[^>]*>([\s\S]*?)<\/(?:icon|app-icon)>/g;
    // Icon objects and inputs, e.g. { content: 'add' } or icon: 'add'
    const icon_props = /\b(?:content|icon)\s*:\s*['"`]([a-z0-9_]+)['"`]/g;
    for await (const file of new Glob('src/app/**/*.ts').scan()) {
        if (file.includes('/mocks/')) continue;
        const text = await Bun.file(file).text();
        for (const [, inner] of text.matchAll(icon_tags)) {
            for (const [word] of inner.matchAll(/[a-z0-9_]+/g)) words.add(word);
        }
        for (const [, word] of text.matchAll(icon_props)) words.add(word);
    }
    return words;
}

const glyphs = await fontGlyphs();
// Single letters and digits are glyphs too, but not icons
const icons = [...(await sourceWords())]
    .filter((w) => w.length > 1 && glyphs.has(w))
    .sort();
// Letters and digits are the input of the icon ligatures
const text = 'abcdefghijklmnopqrstuvwxyz0123456789_';
// No layout closure, so only the ligatures of the kept icons stay
await $`python3 -m fontTools.subset ${FONT} --output-file=${SUBSET} --flavor=woff2 --text=${text} --glyphs=${icons.join(',')} --layout-features=rlig --no-layout-closure --no-hinting --desubroutinize`;
await Bun.write(
    NAMES,
    `// Generated by config/icon-subset.ts. Do not edit.\n\n/** Icons in the subset icon font */\nexport const ICON_SUBSET: ReadonlySet<string> = new Set(${JSON.stringify(icons, null, 4).replace(/"/g, "'")});\n`,
);
await $`bunx prettier --write ${NAMES}`.quiet();
console.log(
    `${icons.length} icons, ${(Bun.file(SUBSET).size / 1024).toFixed(1)} KB`,
);
